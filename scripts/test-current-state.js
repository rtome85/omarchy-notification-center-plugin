const assert = require("node:assert/strict");
const logic = require("../NotificationLogic.js");
const entry = { key: "100-1", originalId: 12, app: "Test", summary: "<img src='https://invalid/'>", ts: 1234, appIcon: "test" };
const live = logic.parseCurrentRows(JSON.stringify([entry]), true);
assert.equal(live[0].timestamp, 1234000);
assert.equal(live[0].originalId, 12);
assert.equal(live[0].isLive, true);
assert.equal(live[0].summary, entry.summary);
assert.deepEqual(logic.parseCurrentRows("broken", true), []);
assert.deepEqual(logic.parseCurrentRows("{}", true), []);
assert.deepEqual(logic.parseCurrentRows(JSON.stringify([{...entry, key: "../bad"}, {...entry, ts: "1234"}]), true), []);
assert.equal(logic.parseCurrentRows(JSON.stringify([{...entry, appIcon: "https://invalid/icon", originalId: -1}]), true)[0].appIcon, "");
assert.equal(logic.parseCurrentRows(JSON.stringify([{...entry, originalId: -1}]), true)[0].originalId, 0);
const history = logic.parseCurrentRows(JSON.stringify([entry, {...entry, key: "100-2", ts: 1000}]), false);
assert.equal(logic.mergeCurrentRows(live, history, {}).length, 2);
assert.equal(logic.mergeCurrentRows(live, history, {})[0].isLive, true);
assert.equal(logic.mergeCurrentRows(live, history, {"100-1": true}).length, 1);
assert.deepEqual(logic.parseCurrentRows(" ".repeat(3276801), true), []);
const fs = require("node:fs");
const qml = fs.readFileSync(require("node:path").join(__dirname, "../BarWidget.qml"), "utf8");
assert.ok(!qml.includes("firstPartyServiceFor"));
assert.equal((qml.match(/\bText\s*\{/g) || []).length, 11);
for (const block of qml.split(/\bText\s*\{/).slice(1)) assert.match(block.split("}")[0], /textFormat: Text.PlainText/);
console.log("Current notification state regression checks passed");
